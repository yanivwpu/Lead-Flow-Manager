import test from 'node:test';
import assert from 'node:assert/strict';
import { inspectConsentTheme } from '../server/ecommerce/shopifyConsentStorefront';
import { createConsentThemeService } from '../server/ecommerce/shopifyConsentThemeService';
import { CatalogApiError } from '../server/salesCatalog/shopify/api';

// Synthetic shape fixtures, not an export of the pilot's unavailable theme file.
const uid = '490ef38e-bb3d-fa92-4a1e-2c4bc52c21d8d951047c';
const type = `shopify://apps/whachatcrm/blocks/whatsapp-consent/${uid}`;
const block = {type, disabled:false};
const theme = (blocks: any = {embed:block}) => ({themes:{nodes:[{role:'MAIN',processing:false,processingFailed:false,
  files:{nodes:[{filename:'config/settings_data.json',body:{content:JSON.stringify({current:{blocks}})}}]}}]}});
const check = (payload: any, state: string, verificationReason: string) =>
  assert.deepEqual(inspectConsentTheme(payload,uid),{state,verificationReason});

test('published detection identifies exact missing/disabled/mismatched/ambiguous block causes without theme data', () => {
  check(theme(),'enabled_verified','block_enabled');
  check(theme({embed:{...block,disabled:true}}),'disabled_verified','block_disabled');
  check(theme({}),'disabled_verified','block_missing');
  check(theme({embed:{...block,type:type.replace('/whatsapp-consent/','/different-handle/')}}),'disabled_verified','wrong_handle');
  check(theme({embed:{...block,type:type.replace(uid,uid.slice(0,-1)+'a')}}),'disabled_verified','extension_id_mismatch');
  check(theme({embed:{type}}),'unverified','enabled_flag_missing');
  for(const disabled of [null,'false',0,{},[]]) check(theme({embed:{type,disabled}}),'unverified','enabled_flag_invalid');
  check(theme({a:block,b:block}),'unverified','duplicate_block');
  const preset = theme({});
  preset.themes.nodes[0].files.nodes[0].body.content=JSON.stringify({current:{blocks:{}},presets:{old:{blocks:{embed:block}}}});
  check(preset,'disabled_verified','block_missing');
  const renamed = theme({embed:{...block,type:type.replace('/whachatcrm/','/new-app-slug/')}});
  check(renamed,'enabled_verified','block_enabled');
});

test('missing files and malformed responses stay unverified; error categories never echo raw contents', () => {
  check({},'unverified','malformed_graphql');
  check({...theme(),errors:[{message:'PRIVATE_PROVIDER_ERROR'}]},'unverified','malformed_graphql');
  check({themes:{nodes:[]}},'not_supported','no_published_theme');
  for(const nodes of [null,{},[null,null]]) check({themes:{nodes}},'unverified','malformed_graphql');
  const wrongTheme=theme();wrongTheme.themes.nodes[0].role='UNPUBLISHED';check(wrongTheme,'unverified','theme_not_main');
  const processing=theme();processing.themes.nodes[0].processing=true;check(processing,'unverified','theme_processing');
  const absent=theme();absent.themes.nodes[0].files.nodes=[];check(absent,'unverified','settings_file_missing');
  const malformed=theme();(malformed.themes.nodes[0].files as any).nodes={};check(malformed,'unverified','malformed_graphql');
  const duplicate=theme();duplicate.themes.nodes[0].files.nodes.push(duplicate.themes.nodes[0].files.nodes[0]);check(duplicate,'unverified','malformed_graphql');
  for(const [content,reason] of [[null,'settings_content_invalid'],['private-token customer-data raw-invalid-json','settings_json_invalid'],
    [JSON.stringify({current:null}),'current_settings_invalid'],[JSON.stringify({current:{blocks:[]}}),'blocks_invalid']] as const){
    const payload=theme();(payload.themes.nodes[0].files.nodes[0].body as any).content=content;
    check(payload,'unverified',reason);
    assert.ok(!JSON.stringify(inspectConsentTheme(payload,uid)).includes('private-token'));
  }
  const commented=theme();commented.themes.nodes[0].files.nodes[0].body.content='/* generated by Shopify */\n'+commented.themes.nodes[0].files.nodes[0].body.content;
  check(commented,'enabled_verified','block_enabled');
});

test('service diagnostics distinguish authorization, throttling and GraphQL failure without provider messages or credentials', async () => {
  const env={SHOPIFY_API_KEY:'a'.repeat(32),SHOPIFY_CONSENT_EXTENSION_RELEASED_VERSION:'reviewed',SHOPIFY_CONSENT_EXTENSION_ID:uid};
  const install={shop:'first.myshopify.com',token:'PRIVATE_TOKEN',connection:'PRIVATE_FINGERPRINT',setup:{}};
  for(const [error,reason] of [[new CatalogApiError('access_denied'),'unauthorized'],[new CatalogApiError('throttled'),'throttled'],
    [new CatalogApiError('invalid_response'),'malformed_graphql'],[Error('raw-provider-message PRIVATE_TOKEN customer@example.test'),'provider_unavailable']] as const){
    const service=createConsentThemeService({env,installation:async()=>install,request:async()=>{throw error;}});
    const result=await service('owner',true);
    assert.equal(result?.state,'unverified');assert.equal(result?.verificationReason,reason);assert.equal(result?.editorUrl,null);
    for(const secret of ['PRIVATE_TOKEN','PRIVATE_FINGERPRINT','raw-provider-message','customer@example.test']) assert.ok(!JSON.stringify(result).includes(secret));
  }
  const service=createConsentThemeService({env,installation:async()=>install,request:async(_s,_t,q)=>q.includes('ConsentThemeAccess')?
    {shop:{myshopifyDomain:install.shop},currentAppInstallation:{accessScopes:[{handle:'read_themes'},{handle:'write_app_proxy'}]}}:theme({embed:{type}})});
  assert.equal((await service('owner',true))?.verificationReason,'enabled_flag_missing');
  assert.equal((await service('owner',true))?.state,'unverified','missing enabled flag is uncertainty, not proof of either toggle state');
});
