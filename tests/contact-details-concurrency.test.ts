import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { transform } from "esbuild";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { getTableConfig } from "drizzle-orm/pg-core";
import { eq, and, sql } from "drizzle-orm";
import { contacts } from "../shared/schema";

test("actual storage update rejects stale identity edits atomically and retains synchronized fields", async () => {
  const database = new PGlite();
  const db = drizzle(database);
  const quote = (name: string) => '"' + name.replaceAll('"', '""') + '"';
  const columns = getTableConfig(contacts).columns.map(column => quote(column.name) + " " + (column.enumValues?.length ? "text" : column.getSQLType()));
  await database.exec(`CREATE TABLE contacts (${columns.join(", ")})`);
  const beforeAt = new Date("2026-10-01T10:00:00Z"), syncAt = new Date("2026-10-01T10:01:00Z");
  await db.insert(contacts).values({ id: "contact", userId: "owner", name: "Original", updatedAt: beforeAt });
  const source = readFileSync("server/storage.ts", "utf8");
  const start = source.indexOf("  async updateContact(\n"), end = source.indexOf("  async deleteContact", start);
  const compiled = await transform(`export class StorageFixture { ${source.slice(start, end)} }`, { loader: "ts", format: "cjs", target: "es2022" });
  const module = { exports: {} as any };
  new Function("db", "contacts", "eq", "and", "sql", "module", "exports", compiled.code)(db, contacts, eq, and, sql, module, module.exports);
  const storage = new module.exports.StorageFixture();
  storage.getContact = async () => (await db.select().from(contacts).where(eq(contacts.id, "contact")))[0];
  await db.update(contacts).set({ name: "Shopify synchronized", updatedAt: syncAt, customFields: { shopifyCustomerId: "123" } }).where(eq(contacts.id, "contact"));
  const stale = await storage.updateContact("contact", { name: "Stale draft" }, { expectedWorkspaceUserId: "owner", expectedUpdatedAt: beforeAt, skipAutomationHooks: true });
  assert.equal(stale, undefined);
  const foreign = await storage.updateContact("contact", { tag: "Changed" }, { expectedWorkspaceUserId: "other", expectedUpdatedAt: syncAt, skipAutomationHooks: true });
  assert.equal(foreign, undefined);
  const syncedIdentity = await storage.updateContact("contact", { name: "Overwrite" }, { expectedWorkspaceUserId: "owner", expectedUpdatedAt: syncAt, requireUnsyncedIdentity: true, skipAutomationHooks: true });
  assert.equal(syncedIdentity, undefined);
  const saved = await storage.updateContact("contact", { tag: "Hot" }, { expectedWorkspaceUserId: "owner", expectedUpdatedAt: syncAt, skipAutomationHooks: true });
  assert.equal(saved.name, "Shopify synchronized"); assert.equal(saved.tag, "Hot"); assert.deepEqual(saved.customFields, { shopifyCustomerId: "123" });
  await db.update(contacts).set({ updatedAt: sql`'2026-10-01 12:00:00.789123'::timestamp` }).where(eq(contacts.id, "contact"));
  const precise = await storage.updateContact("contact", { tag: "Warm" }, { expectedWorkspaceUserId: "owner", expectedUpdatedAt: new Date("2026-10-01T12:00:00.789Z"), skipAutomationHooks: true });
  assert.equal(precise.tag, "Warm");
  await database.close();
});
