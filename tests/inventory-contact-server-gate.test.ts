import assert from "node:assert/strict";
import { executeWorkflowActions, runW2QualificationEngine } from "../server/workflowEngine";
import { scheduleW2FollowUpTimers } from "../server/automationTimerHandlers";
import { storage } from "../server/storage";
import { db } from "../drizzle/db";
import { findMatchingListingsForContact, getInventoryMatchSummaryForContact } from "../server/inventory/inventoryMatchingService";
import { processInventoryOpportunitiesAfterSync, findInventoryOpportunitiesForContact } from "../server/inventory/inventoryOpportunityService";
import { shouldRunBuyerPreferencePipeline } from "../server/buyerPreferenceService";
import { isInventoryContactEligible, isRgeContactEligible } from "../server/inventory/inventoryContactEligibility";

const stale = {schemaVersion: 1, profileStatus: "partial", bedsMin: {value: 11, source: "inferred", confidence: .9, updatedAt: "2026-01-01"}};
let owner = "tenant-a";
let message = "החוב שלך כרגע $1000\nכולל החידוש עד 11/21\nוהדוח"; // Production false-positive wording; amount anonymized.
const contact = () => ({id: "car-rental", userId: owner, customFields: {leadType: "buyer"}, buyerPreferenceProfile: stale}) as any;
const originals = {getMessage: storage.getMessage, getConversation: storage.getConversation, getContacts: storage.getContacts, getContact: storage.getContact, getContactWithConversations: storage.getContactWithConversations, getMessages: storage.getMessages, getTemplateInstall: storage.getTemplateInstall};
const pool = db.$client;
const originalQuery = pool.query;
let sqlReads = 0;
(pool as any).query = () => { sqlReads++; throw new Error("Unexpected database access before intent gate"); };
(storage as any).getContacts = async () => [contact()];
(storage as any).getContact = async () => contact();
(storage as any).getContactWithConversations = async () => ({contact: contact(), conversations: [{id: "conversation", userId: owner}]});
(storage as any).getMessages = async () => [{direction: "inbound", content: message}];
(storage as any).getTemplateInstall = async () => ({installStatus: "installed"});
process.env.INVENTORY_CONNECTOR_ENABLED = "true";
try {
  const result = await findMatchingListingsForContact("car-rental", "tenant-a");
  assert.equal(result.eligible, false);
  assert.equal(result.reason, "contact_intent_ineligible");
  assert.equal(await getInventoryMatchSummaryForContact("car-rental", "tenant-a"), "");
  assert.equal((await findInventoryOpportunitiesForContact("car-rental", "tenant-a")).eligible, false);
  assert.equal((await shouldRunBuyerPreferencePipeline("tenant-a", contact())).ok, false);
  assert.equal(await isRgeContactEligible(contact()), false);
  assert.deepEqual((await runW2QualificationEngine("tenant-a", {} as any, message, contact())).fieldUpdates, {}, "no buyer classification from unrelated thread");
  const workflow = { userId: "tenant-a", triggerConditions: { templateId: "realtor-growth-engine", templateKey: "W1" }, actions: [{type: "send_message", value: "Never send"}] } as any;
  assert.equal((await executeWorkflowActions(workflow, null, {}, contact())).blockedReason, "contact_intent_ineligible");
  await scheduleW2FollowUpTimers({userId: "tenant-a", contactId: "car-rental", qualificationText: "Never send", routingText: null, snapshotInboundAt: null});
  assert.equal((await processInventoryOpportunitiesAfterSync("tenant-a", [{ listingId: "listing", syncAlertStatus: "new", previousPriceCents: null, currentPriceCents: 50000000, priceReduced: false }])).createdOrUpdated, 0);
  assert.equal(sqlReads, 0, "no scoring, listing query, saved-match lookup or AI enrichment for unrelated contacts");
  owner = "tenant-b";
  assert.equal((await findMatchingListingsForContact("car-rental", "tenant-a")).httpStatus, 403);
  assert.equal((await findInventoryOpportunitiesForContact("car-rental", "tenant-a")).httpStatus, 403);
  assert.equal((await shouldRunBuyerPreferencePipeline("tenant-a", contact())).ok, false);
  assert.equal(sqlReads, 0);
  owner = "tenant-a";
  message = "I want to buy a condo in Pompano under $500k";
  assert.equal(await isInventoryContactEligible(contact()), true);
  message = "I want to sell my phone";
  assert.equal(await isRgeContactEligible(contact()), false);
  message = "I want to sell my house";
  assert.equal(await isRgeContactEligible(contact()), true, "seller workflows remain eligible");
  assert.equal(await isInventoryContactEligible({...contact(), buyerPreferenceProfile: {...stale, agentConfirmedAt: "2026-11-16"}}), true);
  message = "Hi, how are you?";
  (storage as any).getMessage = async () => ({direction: "inbound", conversationId: "old-buyer-thread", content: "I want to buy a condo in Pompano under $500k"});
  let referenceOwner = "tenant-a";
  (storage as any).getConversation = async () => ({userId: referenceOwner, contactId: "car-rental"});
  const referencedProfile = {...stale, bedsMin: {...stale.bedsMin, messageId: "old-intent-message"}};
  assert.equal(await isInventoryContactEligible(contact(), referencedProfile), true, "validated old buyer evidence survives neutral recent messages");
  referenceOwner = "tenant-b";
  assert.equal(await isInventoryContactEligible(contact(), referencedProfile), false, "cross-tenant saved evidence reference denied");
  console.log("PASS server matching, AI, opportunity, extraction and tenant gates");
} finally {
  Object.assign(storage, originals);
  pool.query = originalQuery;
}
