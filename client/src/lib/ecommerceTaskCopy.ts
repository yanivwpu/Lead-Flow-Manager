export function useEcommerceTaskCopy() {
  const { i18n } = useTranslation();
  const locale = (i18n.resolvedLanguage || i18n.language || "en").split("-")[0];
  return { locale, dir: locale === "he" ? "rtl" as const : "ltr" as const,
    c: (value: keyof typeof copy): string => locale === "es" || locale === "he" ? copy[value][locale] : value };
}
